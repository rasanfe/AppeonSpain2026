using FicharApi.Models;

namespace FicharApi.Services
{
    /// <summary>
    /// Tickets de un solo uso para el salto PowerBuilder -> web embebida.
    /// Viven en memoria y caducan en segundos: no hacen falta ni tabla ni Redis.
    /// </summary>
    public interface ITicketService
    {
        string Crear(Usuarios usuario, int segundosDeVida);

        /// <summary>Canjea el ticket. Devuelve null si no existe, caduco o ya se uso.</summary>
        Usuarios? Canjear(string ticket);
    }
}
