import { StrictMode } from 'react'
import { createRoot } from 'react-dom/client'
import App from './App'
import './index.css'

/**
 * La PWA instalada arranca de lo que el service worker tiene precacheado: si hay
 * una version nueva, el service worker se la traga en segundo plano pero la
 * pantalla sigue siendo la VIEJA hasta que se vuelve a abrir. Eso es lo que hace
 * pensar que un cambio "no ha entrado". Aqui se recarga en cuanto el service
 * worker nuevo toma el mando, para que la app del movil no vaya un arranque por
 * detras el dia de la charla.
 */
if ('serviceWorker' in navigator && navigator.serviceWorker.controller) {
  let recargando = false
  navigator.serviceWorker.addEventListener('controllerchange', () => {
    if (recargando) return
    recargando = true
    window.location.reload()
  })
}

createRoot(document.getElementById('root')!).render(
  <StrictMode>
    <App />
  </StrictMode>,
)
